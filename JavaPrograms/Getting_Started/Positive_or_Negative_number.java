package Getting_Started;

public class Positive_or_Negative_number {
    public static void main(String[] args) {
        int n = 0;
        if(n>0)
        {
            System.out.println("Positive");
        }
        else if(n<0)
        {
            System.out.println("Negative");
        }
        else
        {
            System.out.println("Zero");
        }
    }
}
